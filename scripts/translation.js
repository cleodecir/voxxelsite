function translate(lang) {
  translationsSection.forEach((translation) => {
    let element = document.getElementById(translation.id);
    if (!element) {
      element = document.getElementsByClassName(translation.id);
      Array.from(element).forEach((e) => {
        e.classList.add("hidden");
        if (lang === "pt") {
          e.innerHTML = translation.en;
        } else {
          e.innerHTML = translation.pt;
        }
        e.classList.remove("hidden");
      });
    } else {
      element.classList.add("hidden");

      // Wait for the transition to complete before changing the text
      setTimeout(() => {
        if (lang === "pt") {
          element.innerHTML = translation.en;
        } else {
          element.innerHTML = translation.pt;
        }

        // Remove the 'hidden' class to start the fade in transition
        element.classList.remove("hidden");
      }, 500); // This should match the duration of the CSS transition
    }
  });
}

document.addEventListener("DOMContentLoaded", (event) => {
  const icon = document.getElementById("trigger-icon");

  // Function to apply the translation based on the saved state
  function applyTranslation() {
    let currentFlag = localStorage.getItem("flag") || "UnitedStatesFlag.png";
    icon.src = `./assets/${currentFlag}`;

    // Check current language and apply translation if necessary
    let currentLang = document.documentElement.lang;

    if (currentFlag === "BrasilFlag.png" && currentLang !== "pt") {
      translate("pt");
    } else if (currentFlag === "UnitedStatesFlag.png" && currentLang !== "en") {
      translate("en");
    }
  }

  // Apply the translation on page load
  applyTranslation();

  icon.addEventListener("click", () => {
    console.log("click");
    // Add the 'hidden' class to start the fade out transition
    icon.classList.add("hidden");
    let currentFlag = icon.src.split("/").pop(); // Getting the name of the asset

    // Wait for the transition to complete
    setTimeout(() => {
      // Change the image source and update the translation state
      if (currentFlag === "UnitedStatesFlag.png") {
        icon.src = "./assets/BrasilFlag.png";
        localStorage.setItem("flag", "BrasilFlag.png");

        translate("pt");
      } else {
        icon.src = "./assets/UnitedStatesFlag.png";
        localStorage.setItem("flag", "UnitedStatesFlag.png");

        translate("en");
      }

      // Remove the 'hidden' class to start the fade in transition
      icon.classList.remove("hidden");
    }, 500); // This should match the duration of the CSS transition
  });
});
